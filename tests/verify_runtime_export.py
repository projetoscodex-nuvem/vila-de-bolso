#!/usr/bin/env python3
"""Real Godot resource exports and isolated runtime regression (NOT Android).

Negative ZIP mutations and the APK-shaped wrapper are SIMULATED FIXTURES.
The valid ZIP/PCK are generated by the locked Godot using the Android preset.
"""
from configparser import ConfigParser
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from check_runtime_pack import check_pack

SCRIPTS = ['core/world_data', 'core/map_camera', 'core/gesture_router',
           'core/save_store', 'presentation/map_view']
ALLOWED_EDITOR_ERRORS = {
    'ERROR: Condition "_sock == -1" is true. Returning: FAILED',
    'ERROR: Condition "err != OK" is true. Returning: ERR_CANT_CREATE',
}


def suite():
    godot = os.environ['GODOT_BIN']
    build = ROOT / 'build/runtime_export'
    build.mkdir(parents=True, exist_ok=True)
    cases = []
    lock = json.loads((ROOT / 'scripts/toolchain.lock.json').read_text())
    assert subprocess.check_output([godot, '--version'], text=True).strip() == lock['godot_version']
    with tempfile.TemporaryDirectory(prefix='vila-export-regression-') as temp:
        source = Path(temp)
        for name in ['project.godot', 'export_presets.cfg']:
            shutil.copyfile(ROOT / name, source / name)
        for name in ['assets', 'core', 'presentation', 'scenes', 'data', 'licenses']:
            shutil.copytree(ROOT / name, source / name)
        # Sentinels: these must never appear in a runtime pack.
        for name in ['tests/private.gd', 'scripts/private.gd', 'reports/private.txt',
                     'references/private.txt', 'build/private.txt', '.tools/private.txt',
                     '.env', 'private.keystore', 'private.jks', 'export_credentials.cfg']:
            path = source / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text('# FIXTURE sentinel - must be excluded\nextends RefCounted\n' if path.suffix == '.gd' else 'FIXTURE sentinel - must be excluded\n')

        def command(args, label):
            result = subprocess.run([godot, '--headless', '--path', str(source)] + args,
                                    text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=90)
            (build / (label + '.log')).write_text(result.stdout)
            errors = [line for line in result.stdout.splitlines() if line.startswith(('ERROR:', 'SCRIPT ERROR:'))]
            assert result.returncode == 0 and all(line in ALLOWED_EDITOR_ERRORS for line in errors), result.stdout
            if errors:
                print('LIMITATION: editor TCP listeners blocked; exact diagnostics retained in ' + label + '.log')

        def case(label, artifact, expected, detail='', simulated=False):
            passed, log = check_pack(artifact, godot)
            (build / (label + '.log')).write_text(log)
            assert passed == expected and detail in log, label + '\n' + log
            cases.append({'case': label, 'expected_runtime': 'PASS' if expected else 'FAIL', 'result': 'PASS',
                          'classification': 'SIMULATED_FIXTURE' if simulated else 'REAL_GODOT_RESOURCE_EXPORT'})
            print('PASS: ' + label + (' (SIMULATED FIXTURE)' if simulated else ' (real Godot export)'))

        command(['--editor', '--quit'], 'import')
        preset = source / 'export_presets.cfg'
        fixed = preset.read_text()
        old = re.sub(r'export_filter="resources"', 'export_filter="scenes"', fixed)
        old = re.sub(r'^export_files=.*$', 'export_files=PackedStringArray("res://scenes/main.tscn")', old, flags=re.M)
        preset.write_text(old)
        before = build / 'previous-scenes-filter.zip'
        command(['--export-pack', 'Android Debug', str(before)], 'export_before')
        case('previous_scenes_filter_missing_dependencies', before, False, 'res://core/world_data.gd')
        preset.write_text(fixed)
        exported = build / 'runtime.zip'
        command(['--export-pack', 'Android Debug', str(exported)], 'export_zip')
        case('exported_zip_scene_menu', exported, True)
        pck = build / 'runtime.pck'
        command(['--export-pack', 'Android Debug', str(pck)], 'export_pck')
        case('exported_native_pck_scene_menu', pck, True)
        with zipfile.ZipFile(exported) as archive:
            files = {name: archive.read(name) for name in archive.namelist()}
        assert all(path + '.gdc' in files and path + '.gd.remap' in files for path in SCRIPTS)
        assert not any(path.startswith(('tests/', 'scripts/', 'reports/', 'references/', 'build/', '.tools/')) for path in files)

        def fixture(label, remove=(), replace=None, apk=False):
            path = build / (label + ('.apk' if apk else '.zip'))
            with zipfile.ZipFile(path, 'w') as archive:
                for name, payload in files.items():
                    if name not in remove:
                        archive.writestr(('assets/' if apk else '') + name, (replace or {}).get(name, payload))
                if apk:
                    archive.writestr('AndroidManifest.xml', b'FAKE WRAPPER: NOT AN ANDROID APK')
                for name, payload in (replace or {}).items():
                    if name not in files:
                        archive.writestr(name, payload)
            return path

        case('apk_shaped_fixture_real_exported_assets', fixture('apk_fixture', apk=True), True, simulated=True)
        for script in SCRIPTS:
            label = 'missing_' + script.replace('/', '_')
            case(label, fixture(label, [script + '.gdc', script + '.gd.remap']), False, 'res://' + script + '.gd', simulated=True)
        case('broken_compiled_remap', fixture('broken_compiled', ['core/world_data.gdc']), False, 'missing remap target', simulated=True)
        case('corrupt_compiled_script', fixture('corrupt_compiled', replace={'core/world_data.gdc': b'FAKE INVALID BYTECODE'}), False, simulated=True)
        config = ConfigParser()
        config.read_string(files['scenes/main.tscn.remap'].decode())
        scene_target = config['remap']['path'].strip('"').removeprefix('res://')
        case('missing_binary_scene', fixture('missing_scene', [scene_target]), False, 'missing remap target', simulated=True)
        case('missing_exported_project_settings', fixture('missing_project_settings', ['project.binary']), False, simulated=True)
        case('missing_world_data', fixture('missing_data', ['data/world.json']), False, 'world data', simulated=True)
        case('excluded_test_resource', fixture('excluded_test', replace={'tests/private.gd': b'FIXTURE'}), False, 'unexpected runtime directory: tests', simulated=True)
        summary = {
            'classification': 'REAL_GODOT_RESOURCE_EXPORT_AND_HEADLESS_RUNTIME',
            'source_snapshot': 'working tree; final tested commit reconciled in PR',
            'godot_version': lock['godot_version'], 'android_physical': 'NOT_RUN',
            'apk_generated': False, 'apk_wrapper_and_negative_mutations': 'SIMULATED_FIXTURES',
            'cases': cases, 'exported_zip_members': sorted(files),
            'zip_sha256': hashlib.sha256(exported.read_bytes()).hexdigest(),
            'pck_sha256': hashlib.sha256(pck.read_bytes()).hexdigest(),
        }
        (build / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(f'PASS: runtime export regression cases={len(cases)} failures=0; Android physical NOT_RUN; no real APK produced')


if __name__ == '__main__':
    suite()
